"""SQLite tables. Geometry and event payloads are stored as JSON."""

from datetime import datetime, timezone
from typing import Any

from sqlalchemy import JSON, Column
from sqlmodel import Field, SQLModel


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Project(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    name: str
    created_at: datetime = Field(default_factory=utcnow)


class Label(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    project_id: int = Field(foreign_key="project.id", index=True)
    name: str
    color: str


class Image(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    project_id: int = Field(foreign_key="project.id", index=True)
    filename: str  # original upload name
    stored_name: str  # file name inside IMAGES_DIR
    width: int
    height: int
    status: str = "new"  # new | in_progress | done
    created_at: datetime = Field(default_factory=utcnow)


class Annotation(SQLModel, table=True):
    id: str = Field(primary_key=True)  # generated by the client
    image_id: int = Field(foreign_key="image.id", index=True)
    label_id: int = Field(foreign_key="label.id")
    kind: str  # box | polygon
    # box: {"x","y","w","h"}; polygon: {"points": [x0, y0, x1, y1, ...]} in image pixels
    geometry: dict[str, Any] = Field(sa_column=Column(JSON, nullable=False))
    source: str  # manual | ai | ai_edited
    score: float | None = None
    created_at: datetime = Field(default_factory=utcnow)
    updated_at: datetime = Field(default_factory=utcnow)


class LabelingSession(SQLModel, table=True):
    """One sitting of labeling in one mode; groups effort events for the study."""

    id: int | None = Field(default=None, primary_key=True)
    project_id: int = Field(foreign_key="project.id", index=True)
    mode: str  # manual | ai
    participant: str = ""
    started_at: datetime = Field(default_factory=utcnow)


class Event(SQLModel, table=True):
    """Append-only effort / inference log. Stats are computed from this table."""

    id: int | None = Field(default=None, primary_key=True)
    project_id: int = Field(foreign_key="project.id", index=True)
    session_id: int | None = Field(default=None, foreign_key="labelingsession.id", index=True)
    image_id: int | None = None
    annotation_id: str | None = None
    mode: str | None = None
    kind: str
    ts: datetime = Field(default_factory=utcnow)
    payload: dict[str, Any] = Field(default_factory=dict, sa_column=Column(JSON, nullable=False))
